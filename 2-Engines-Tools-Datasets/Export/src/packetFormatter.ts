/**
 * Packet Formatter — Shared Formatting Utilities
 *
 * Provides consistent formatting functions used by all export generators:
 * - Header generation with domain branding and metadata
 * - Section formatting with consistent structure
 * - Timestamp formatting (ISO 8601 and human-readable)
 * - Provenance display with kernel attribution
 * - Print-ready layout helpers
 */

// ── Constants ──────────────────────────────────────────────────

const DOMAIN_NAME = '10-business-law-accounting';
const DOMAIN_LABEL = 'Business / Law / Accounting';
const SEPARATOR = '════════════════════════════════════════════════════════════';
const SUBSEPARATOR = '────────────────────────────────────────────────────────────';

// ── Timestamp Formatting ───────────────────────────────────────

/**
 * Formats a Date to ISO 8601 string.
 * Also supports returning human-readable format when specified.
 */
export function formatTimestamp(date: Date, format: 'iso' | 'human' = 'iso'): string {
  if (format === 'human') {
    return date.toLocaleDateString('en-CA', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      timeZoneName: 'short',
    });
  }
  return date.toISOString();
}

// ── Header Generation ──────────────────────────────────────────

/**
 * Generates a formatted packet header with domain branding and metadata.
 */
export function formatPacketHeader(params: {
  packetType: string;
  title: string;
  generatedAt: string;
  entityId?: string;
  matterId?: string;
}): string {
  const lines: string[] = [
    SEPARATOR,
    `  ${DOMAIN_LABEL}`,
    `  ${params.packetType}`,
    SEPARATOR,
    '',
    `  Title:      ${params.title}`,
    `  Generated:  ${params.generatedAt}`,
  ];

  if (params.entityId) {
    lines.push(`  Entity ID:  ${params.entityId}`);
  }
  if (params.matterId) {
    lines.push(`  Matter ID:  ${params.matterId}`);
  }

  lines.push('');
  lines.push(SUBSEPARATOR);

  return lines.join('\n');
}

// ── Section Formatting ─────────────────────────────────────────

/**
 * Formats a named section with consistent structure.
 */
export function formatSection(sectionName: string, content: string): string {
  const lines: string[] = [
    '',
    `  ${sectionName.toUpperCase()}`,
    SUBSEPARATOR,
    '',
    `  ${content}`,
    '',
  ];
  return lines.join('\n');
}

// ── Provenance Display ─────────────────────────────────────────

/**
 * Formats a provenance entry showing kernel attribution and actor.
 */
export function formatProvenance(params: {
  sourceKernel: string;
  action: string;
  actor: string;
  timestamp: string;
  detail?: string;
}): string {
  const lines: string[] = [
    `  [${params.sourceKernel.toUpperCase()}] ${params.action}`,
    `    Actor:     ${params.actor}`,
    `    Timestamp: ${params.timestamp}`,
  ];

  if (params.detail) {
    lines.push(`    Detail:    ${params.detail}`);
  }

  return lines.join('\n');
}

// ── Print Layout Helpers ───────────────────────────────────────

/**
 * Wraps a complete packet in a print-ready layout with header and footer.
 */
export function formatPrintLayout(params: {
  header: string;
  sections: string[];
  footer?: string;
}): string {
  const parts: string[] = [
    params.header,
    ...params.sections,
    '',
    SEPARATOR,
    `  Generated by ${DOMAIN_NAME}`,
    `  This document is a point-in-time export and may not reflect current state.`,
    SEPARATOR,
  ];

  if (params.footer) {
    parts.push('', params.footer);
  }

  return parts.join('\n');
}
